// ==========================================================================
// ESQUEMA DE LA BASE DE DATOS (Postgres en Neon) CON DRIZZLE
//
// Fuente única del esquema: las migraciones de db/migraciones/ se generan a
// partir de este archivo (npm run db:generar). Lo que Drizzle no sabe expresar
// (extensión unaccent, trigger, datos iniciales) está en la migración
// 0001_extras.sql.
//
// Nombres: camelCase en TypeScript y snake_case en la base. La conversión la
// hace la opción casing: 'snake_case' (drizzle.config.ts y lib/db.ts), así que
// usuarioId <-> usuario_id sin escribir cada nombre dos veces.
//
// Traducido de esquema_mysql.sql (backend/sql/). Decisiones respecto a MySQL:
//   * snake_case: Postgres pasa a minúsculas los nombres sin comillas.
//   * AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY (permite importar IDs).
//   * DATETIME -> timestamptz.  TINYINT(1) -> boolean.  TINYINT -> smallint.
//   * numeric llega como string ("500.00"), igual que con mysql2.
//   * Índices en las llaves foráneas: InnoDB los crea solo, Postgres no.
// ==========================================================================
import { relations, sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  numeric,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  unique,
  varchar,
} from "drizzle-orm/pg-core";

// Tipos repetidos
const id = () => integer().primaryKey().generatedByDefaultAsIdentity();
const fecha = () => timestamp({ withTimezone: true });
const dinero = () => numeric({ precision: 10, scale: 2 });

// -------------------------------------------------------------- USUARIOS

export const departamentos = pgTable("departamentos", {
  departamentoId: id(),
  nombreDepartamento: varchar({ length: 50 }).notNull().unique(),
});

export const usuarios = pgTable(
  "usuarios",
  {
    usuarioId: id(),
    correoElectronico: varchar({ length: 100 }).notNull().unique(),
    contrasenaHash: varchar({ length: 255 }).notNull(),
    tipoRol: varchar({ length: 20 }).notNull(),
    estadoCuenta: varchar({ length: 20 }).default("Activo"),
    fechaRegistro: fecha().defaultNow(),
    tokenRecuperacion: varchar({ length: 255 }),
    expiracionToken: fecha(),
    // Las cuentas nuevas empiezan en false si la verificación está activa (ver /registro)
    correoVerificado: boolean().notNull().default(true),
    tokenVerificacion: varchar({ length: 64 }),
    expiracionVerificacion: fecha(),
  },
  (t) => [
    check("usuarios_tipo_rol_check", sql`${t.tipoRol} IN ('Proveedor', 'Emprendedor', 'Administrador', 'Admin')`),
    check("usuarios_estado_cuenta_check", sql`${t.estadoCuenta} IN ('Activo', 'Inactivo', 'Suspendido')`),
  ]
);

export const perfilesUsuarios = pgTable(
  "perfiles_usuarios",
  {
    perfilId: id(),
    usuarioId: integer().notNull().unique().references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    nombreRazonSocial: varchar({ length: 150 }).notNull(),
    telefonoWhatsapp: varchar({ length: 20 }).notNull(),
    departamentoId: integer().notNull().references(() => departamentos.departamentoId),
    direccionExacta: varchar({ length: 255 }),
    fotoPerfilUrl: varchar({ length: 255 }),
  },
  (t) => [index("idx_perfiles_departamento").on(t.departamentoId)]
);

export const proveedores = pgTable("proveedores", {
  proveedorId: id(),
  usuarioId: integer().notNull().unique().references(() => usuarios.usuarioId, { onDelete: "cascade" }),
  numeroRuc: varchar({ length: 50 }),
  nombreComercial: varchar({ length: 150 }),
  descripcionEmpresa: text(),
  tipoMateriaPrimaPrincipal: varchar({ length: 100 }),
});

export const emprendedores = pgTable("emprendedores", {
  emprendedorId: id(),
  usuarioId: integer().notNull().unique().references(() => usuarios.usuarioId, { onDelete: "cascade" }),
  nombreMarca: varchar({ length: 150 }),
  especialidadCalzado: varchar({ length: 100 }),
  capacidadProduccionMensual: integer(),
});

export const administradores = pgTable(
  "administradores",
  {
    adminId: id(),
    usuarioId: integer().notNull().references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    nivelAcceso: varchar({ length: 50 }).default("SuperAdmin"),
  },
  (t) => [index("idx_administradores_usuario").on(t.usuarioId)]
);

// fecha_actualizacion la mantiene el trigger trg_verificaciones_fecha_actualizacion
// (migración 0001_extras.sql), que reemplaza a ON UPDATE CURRENT_TIMESTAMP de MySQL.
export const verificacionesAntifraude = pgTable(
  "verificaciones_antifraude",
  {
    verificacionId: id(),
    usuarioId: integer().notNull().unique().references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    correoConfirmado: boolean().default(true),
    cedulaRucSubido: boolean().default(false),
    ubicacionConfirmada: boolean().default(false),
    whatsappVerificado: boolean().default(false),
    fotoIdentidadUrl: varchar({ length: 255 }),
    fotoSelfieUrl: varchar({ length: 255 }),
    estadoFinal: varchar({ length: 20 }).default("Pendiente"),
    fechaActualizacion: fecha().defaultNow(),
  },
  (t) => [
    check(
      "verificaciones_antifraude_estado_final_check",
      sql`${t.estadoFinal} IN ('Pendiente', 'Verificado', 'Rechazado')`
    ),
  ]
);

// -------------------------------------------------------------- MERCADO

export const categoriasMateriales = pgTable("categorias_materiales", {
  categoriaId: id(),
  nombreCategoria: varchar({ length: 50 }).notNull().unique(),
  descripcion: varchar({ length: 255 }),
});

export const ofertas = pgTable(
  "ofertas",
  {
    ofertaId: id(),
    proveedorId: integer().notNull().references(() => usuarios.usuarioId),
    tituloMaterial: varchar({ length: 150 }).notNull(),
    descripcion: varchar({ length: 1000 }),
    categoriaId: integer().notNull().references(() => categoriasMateriales.categoriaId),
    precio: dinero().notNull(),
    unidadMedida: varchar({ length: 30 }).notNull(),
    distanciaSimuladaKm: integer().notNull(),
    fechaPublicacion: fecha().defaultNow(),
    fotos: text(),
  },
  (t) => [index("idx_ofertas_proveedor").on(t.proveedorId), index("idx_ofertas_categoria").on(t.categoriaId)]
);

export const fotosOfertas = pgTable(
  "fotos_ofertas",
  {
    fotoId: id(),
    ofertaId: integer().notNull().references(() => ofertas.ofertaId, { onDelete: "cascade" }),
    fotoUrl: varchar({ length: 255 }).notNull(),
    esPrincipal: boolean().default(false),
    fechaSubida: fecha().defaultNow(),
  },
  (t) => [index("idx_fotos_ofertas_oferta").on(t.ofertaId)]
);

export const subastas = pgTable(
  "subastas",
  {
    subastaId: id(),
    proveedorId: integer().notNull().references(() => usuarios.usuarioId),
    // Publicación de la que sale el lote (NULL si se creó sin publicación o si esta se borró)
    ofertaId: integer().references(() => ofertas.ofertaId, { onDelete: "set null" }),
    categoriaId: integer().references(() => categoriasMateriales.categoriaId),
    tituloLote: varchar({ length: 150 }).notNull(),
    precioBase: dinero().notNull(),
    precioActual: dinero().notNull(),
    fechaInicio: fecha().defaultNow(),
    fechaFin: fecha().notNull(),
    // 'Cancelada': se borró la publicación mientras la subasta seguía abierta
    estado: varchar({ length: 15 }).default("Activa"),
  },
  (t) => [
    check("chk_subastas_estado", sql`${t.estado} IN ('Activa', 'Finalizada', 'Cancelada')`),
    // El cierre de subastas busca las activas ya vencidas
    index("idx_subastas_estado_fin").on(t.estado, t.fechaFin),
    index("idx_subastas_proveedor").on(t.proveedorId),
    index("idx_subastas_oferta").on(t.ofertaId),
    index("idx_subastas_categoria").on(t.categoriaId),
  ]
);

export const pujas = pgTable(
  "pujas",
  {
    pujaId: id(),
    subastaId: integer().notNull().references(() => subastas.subastaId, { onDelete: "cascade" }),
    emprendedorId: integer().notNull().references(() => usuarios.usuarioId),
    montoPuja: dinero().notNull(),
    fechaPuja: fecha().defaultNow(),
  },
  (t) => [index("idx_pujas_subasta").on(t.subastaId), index("idx_pujas_emprendedor").on(t.emprendedorId)]
);

export const tratosCerrados = pgTable(
  "tratos_cerrados",
  {
    tratoId: id(),
    proveedorId: integer().notNull().references(() => usuarios.usuarioId),
    emprendedorId: integer().notNull().references(() => usuarios.usuarioId),
    tipoOrigen: varchar({ length: 20 }).notNull(),
    origenId: integer(),
    descripcionResumen: varchar({ length: 255 }).notNull(),
    montoTotal: dinero().notNull(),
    estadoTrato: varchar({ length: 20 }).default("Completado"),
    fechaCierre: fecha().defaultNow(),
  },
  (t) => [
    check("tratos_cerrados_tipo_origen_check", sql`${t.tipoOrigen} IN ('Oferta', 'Subasta', 'AcuerdoDirecto')`),
    check(
      "tratos_cerrados_estado_trato_check",
      sql`${t.estadoTrato} IN ('Pendiente', 'EnProceso', 'Completado', 'Cancelado')`
    ),
    index("idx_tratos_proveedor").on(t.proveedorId),
    index("idx_tratos_emprendedor").on(t.emprendedorId),
  ]
);

// -------------------------------------------------------------- COMUNICACIÓN

export const mensajesChat = pgTable(
  "mensajes_chat",
  {
    mensajeId: id(),
    remitenteId: integer().notNull().references(() => usuarios.usuarioId),
    destinatarioId: integer().notNull().references(() => usuarios.usuarioId),
    contenidoTexto: text().notNull(),
    fechaEnvio: fecha().defaultNow(),
    esEntregado: boolean().default(false),
    fechaEntrega: fecha(),
    esLeido: boolean().default(false),
    fechaLectura: fecha(),
  },
  (t) => [
    // Contador de mensajes no leídos
    index("idx_mensajes_no_leidos").on(t.destinatarioId, t.esLeido),
    index("idx_mensajes_remitente").on(t.remitenteId),
  ]
);

export const calificaciones = pgTable(
  "calificaciones",
  {
    calificacionId: id(),
    tratoId: integer()
      .notNull()
      .references(() => tratosCerrados.tratoId, { onDelete: "cascade" }),
    autorId: integer()
      .notNull()
      .references(() => usuarios.usuarioId),
    calificadoId: integer()
      .notNull()
      .references(() => usuarios.usuarioId),
    puntuacion: smallint().notNull(),
    comentario: varchar({ length: 300 }),
    fechaCalificacion: fecha().defaultNow(),
  },
  (t) => [
    check("chk_calificaciones_puntuacion", sql`${t.puntuacion} BETWEEN 1 AND 5`),
    // Una sola calificación por persona y trato
    unique("uq_calificaciones_trato_autor").on(t.tratoId, t.autorId),
    index("idx_calificaciones_calificado").on(t.calificadoId),
    index("idx_calificaciones_autor").on(t.autorId),
  ]
);

export const notificaciones = pgTable(
  "notificaciones",
  {
    notificacionId: id(),
    usuarioId: integer()
      .notNull()
      .references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    // PujaSuperada, PujaRecibida, SubastaGanada, SubastaTerminada, SubastaCancelada,
    // TratoActualizado, CalificacionRecibida, AlertaBusqueda, FavoritoRebajado
    tipo: varchar({ length: 30 }).notNull(),
    titulo: varchar({ length: 120 }).notNull(),
    mensaje: varchar({ length: 300 }).notNull(),
    enlace: varchar({ length: 200 }), // página a la que lleva al hacer clic (p. ej. mercado.html)
    referenciaId: integer(), // subasta_id o trato_id, para no repetir avisos
    esLeida: boolean().notNull().default(false),
    fechaCreacion: fecha().defaultNow(),
  },
  (t) => [index("idx_notificaciones_usuario").on(t.usuarioId, t.esLeida, t.fechaCreacion)]
);

export const favoritos = pgTable(
  "favoritos",
  {
    usuarioId: integer()
      .notNull()
      .references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    ofertaId: integer()
      .notNull()
      .references(() => ofertas.ofertaId, { onDelete: "cascade" }),
    fechaGuardado: fecha().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.usuarioId, t.ofertaId] }), index("idx_favoritos_oferta").on(t.ofertaId)]
);

export const alertasBusqueda = pgTable(
  "alertas_busqueda",
  {
    alertaId: id(),
    usuarioId: integer()
      .notNull()
      .references(() => usuarios.usuarioId, { onDelete: "cascade" }),
    palabraClave: varchar({ length: 60 }),
    categoriaId: integer().references(() => categoriasMateriales.categoriaId, { onDelete: "cascade" }),
    precioMaximo: dinero(),
    fechaCreacion: fecha().defaultNow(),
  },
  (t) => [index("idx_alertas_usuario").on(t.usuarioId), index("idx_alertas_categoria").on(t.categoriaId)]
);

// -------------------------------------------------------------- RELACIONES
// Para las consultas con db.query.* (no cambian la base de datos).

export const usuariosRelaciones = relations(usuarios, ({ one, many }) => ({
  perfil: one(perfilesUsuarios),
  proveedor: one(proveedores),
  emprendedor: one(emprendedores),
  verificacion: one(verificacionesAntifraude),
  ofertas: many(ofertas),
  subastas: many(subastas),
  pujas: many(pujas),
  notificaciones: many(notificaciones),
  favoritos: many(favoritos),
  alertas: many(alertasBusqueda),
}));

export const perfilesUsuariosRelaciones = relations(perfilesUsuarios, ({ one }) => ({
  usuario: one(usuarios, { fields: [perfilesUsuarios.usuarioId], references: [usuarios.usuarioId] }),
  departamento: one(departamentos, {
    fields: [perfilesUsuarios.departamentoId],
    references: [departamentos.departamentoId],
  }),
}));

export const departamentosRelaciones = relations(departamentos, ({ many }) => ({
  perfiles: many(perfilesUsuarios),
}));

export const proveedoresRelaciones = relations(proveedores, ({ one }) => ({
  usuario: one(usuarios, { fields: [proveedores.usuarioId], references: [usuarios.usuarioId] }),
}));

export const emprendedoresRelaciones = relations(emprendedores, ({ one }) => ({
  usuario: one(usuarios, { fields: [emprendedores.usuarioId], references: [usuarios.usuarioId] }),
}));

export const verificacionesAntifraudeRelaciones = relations(verificacionesAntifraude, ({ one }) => ({
  usuario: one(usuarios, { fields: [verificacionesAntifraude.usuarioId], references: [usuarios.usuarioId] }),
}));

export const categoriasMaterialesRelaciones = relations(categoriasMateriales, ({ many }) => ({
  ofertas: many(ofertas),
  subastas: many(subastas),
}));

export const ofertasRelaciones = relations(ofertas, ({ one, many }) => ({
  proveedor: one(usuarios, { fields: [ofertas.proveedorId], references: [usuarios.usuarioId] }),
  categoria: one(categoriasMateriales, {
    fields: [ofertas.categoriaId],
    references: [categoriasMateriales.categoriaId],
  }),
  fotos: many(fotosOfertas),
  subastas: many(subastas),
  favoritos: many(favoritos),
}));

export const fotosOfertasRelaciones = relations(fotosOfertas, ({ one }) => ({
  oferta: one(ofertas, { fields: [fotosOfertas.ofertaId], references: [ofertas.ofertaId] }),
}));

export const subastasRelaciones = relations(subastas, ({ one, many }) => ({
  proveedor: one(usuarios, { fields: [subastas.proveedorId], references: [usuarios.usuarioId] }),
  oferta: one(ofertas, { fields: [subastas.ofertaId], references: [ofertas.ofertaId] }),
  categoria: one(categoriasMateriales, {
    fields: [subastas.categoriaId],
    references: [categoriasMateriales.categoriaId],
  }),
  pujas: many(pujas),
}));

export const pujasRelaciones = relations(pujas, ({ one }) => ({
  subasta: one(subastas, { fields: [pujas.subastaId], references: [subastas.subastaId] }),
  emprendedor: one(usuarios, { fields: [pujas.emprendedorId], references: [usuarios.usuarioId] }),
}));

export const tratosCerradosRelaciones = relations(tratosCerrados, ({ one, many }) => ({
  proveedor: one(usuarios, {
    fields: [tratosCerrados.proveedorId],
    references: [usuarios.usuarioId],
    relationName: "tratosComoProveedor",
  }),
  emprendedor: one(usuarios, {
    fields: [tratosCerrados.emprendedorId],
    references: [usuarios.usuarioId],
    relationName: "tratosComoEmprendedor",
  }),
  calificaciones: many(calificaciones),
}));

export const mensajesChatRelaciones = relations(mensajesChat, ({ one }) => ({
  remitente: one(usuarios, {
    fields: [mensajesChat.remitenteId],
    references: [usuarios.usuarioId],
    relationName: "mensajesEnviados",
  }),
  destinatario: one(usuarios, {
    fields: [mensajesChat.destinatarioId],
    references: [usuarios.usuarioId],
    relationName: "mensajesRecibidos",
  }),
}));

export const calificacionesRelaciones = relations(calificaciones, ({ one }) => ({
  trato: one(tratosCerrados, { fields: [calificaciones.tratoId], references: [tratosCerrados.tratoId] }),
  autor: one(usuarios, {
    fields: [calificaciones.autorId],
    references: [usuarios.usuarioId],
    relationName: "calificacionesHechas",
  }),
  calificado: one(usuarios, {
    fields: [calificaciones.calificadoId],
    references: [usuarios.usuarioId],
    relationName: "calificacionesRecibidas",
  }),
}));

export const notificacionesRelaciones = relations(notificaciones, ({ one }) => ({
  usuario: one(usuarios, { fields: [notificaciones.usuarioId], references: [usuarios.usuarioId] }),
}));

export const favoritosRelaciones = relations(favoritos, ({ one }) => ({
  usuario: one(usuarios, { fields: [favoritos.usuarioId], references: [usuarios.usuarioId] }),
  oferta: one(ofertas, { fields: [favoritos.ofertaId], references: [ofertas.ofertaId] }),
}));

export const alertasBusquedaRelaciones = relations(alertasBusqueda, ({ one }) => ({
  usuario: one(usuarios, { fields: [alertasBusqueda.usuarioId], references: [usuarios.usuarioId] }),
  categoria: one(categoriasMateriales, {
    fields: [alertasBusqueda.categoriaId],
    references: [categoriasMateriales.categoriaId],
  }),
}));

// Contadores de los límites de intentos (lib/limites.ts). Viven en la base para que
// todas las instancias de Vercel cuenten juntas. clave = "<límite>:<ip o u<id>>".
// Las ventanas vencidas se borran en el cron diario (/api/cron/cerrar-subastas).
export const limitesUso = pgTable(
  "limites_uso",
  {
    clave: varchar({ length: 200 }).primaryKey(),
    cuenta: integer().notNull(),
    vence: fecha().notNull(),
  },
  (t) => [index("idx_limites_uso_vence").on(t.vence)]
);
